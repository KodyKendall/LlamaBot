"""Run the dependency-free Node tests for the LP-30 sign-in token retry (never served from the browser cache)."""

import subprocess
from pathlib import Path


def test_ws_token_no_cache_node_suite():
    app_root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [
            "node",
            "--experimental-default-type=module",
            "--test",
            "tests/js/ws_token_no_cache.test.mjs",
        ],
        cwd=app_root,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )

    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
