"""Run the Node test for WebSocket sign-in failure recovery."""

import subprocess
from pathlib import Path


def test_ws_auth_failure_recovery_node_suite():
    app_root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [
            "node",
            "--experimental-default-type=module",
            "--test",
            "tests/js/ws_auth_failure_recovery.test.mjs",
        ],
        cwd=app_root,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )

    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
