"""Run the dependency-free Node test for the chat.html update-button ordering bug (SI#203)."""

import subprocess
from pathlib import Path


def test_update_button_ordering_node_suite():
    app_root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [
            "node",
            "--experimental-default-type=module",
            "--test",
            "tests/js/update_button_ordering.test.mjs",
        ],
        cwd=app_root,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )

    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
