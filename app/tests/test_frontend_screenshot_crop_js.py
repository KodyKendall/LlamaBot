"""Run the dependency-free Node test for cropping screenshots to the iframe."""

import subprocess
from pathlib import Path


def test_screenshot_crops_to_iframe_node_suite():
    app_root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [
            "node",
            "--experimental-default-type=module",
            "--test",
            "tests/js/screenshot_crops_to_iframe.test.mjs",
        ],
        cwd=app_root,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )

    assert result.returncode == 0, f"{result.stdout}\n{result.stderr}"
